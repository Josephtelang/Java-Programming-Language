public class Unary_incre_op02 {
    public static void main(String arg[]){
        // pre increment
        int a = 10 ;
        int b = ++a;
        System.out.println(a);
        System.out.println(b);

        // post increment
        int c = 10;
        int d = c++;
        System.out.println(c);
        System.out.println(d);


    }
    
}
