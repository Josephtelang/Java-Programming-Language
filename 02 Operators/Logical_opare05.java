public class Logical_opare05 {
    public static void main(String arg[]){
        System.out.println( (4>2) && (5>1) );
        System.out.println( (4>6) && (5>1) );

        System.out.println( (4>2) || (5<1) );
        System.out.println( (4<2) || (5<1) );

        System.out.println( !(4>2)  );
        System.out.println( !(4<2)  );
    }
}
