public class Switch_state09 {
    public static void main(String arg[]){
        int num = 2;
        switch(num){
            case 3 : System.out.println("burger");
                            break;
            case 2 : System.out.println("samosa");
                            break;
            case 1 : System.out.println("mango shake");
                            break;
            default : System.out.println("we wake up");
        }
    }
}
